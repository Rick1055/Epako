COLOR_TERRACOTTA = colors.HexColor("#D87D65")     # Clinical alert accent
COLOR_MUTED_BG = colors.HexColor("#F8F6F0")       # Washi linen surface tint


_CHART_LOCK = threading.Lock()


class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute total pages and stamp
    dignified clinical footer with pagination and digital signature hash.
    """
    def __init__(self, *args, session_id=None, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []
        self.session_id = session_id

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int):
        self.saveState()
        self.setFont("Helvetica", 7.5)
        self.setFillColor(COLOR_SLATE)

        # Top subtle running rule
        self.setStrokeColor(COLOR_BORDER)
        self.setLineWidth(0.5)
        self.line(36, 764, 576, 764)

        # Header running line
        self.drawString(36, 768, "Epako Voice AI | Speech Session Report")
        self.drawRightString(576, 768, f"Confidential health information | Session {self.session_id}")

        # Footer running rule
        self.line(36, 32, 576, 32)

        # Footer details
        footer_left = "Generated by Epako Voice AI from recorded session data | A communication and practice aid, not a diagnosis"
        self.drawString(36, 22, footer_left)
        self.drawRightString(576, 22, f"Page {self._pageNumber} of {total_pages}")
        self.restoreState()


def generate_acoustic_charts(metrics: Dict[str, Any], history: Optional[List[Dict[str, Any]]] = None) -> io.BytesIO:
    """
    Generates a composite 2-panel clinical acoustic telemetry figure:
    Panel 1: Vowel Space Area (F1 vs F2 Formant Centralization)
    Panel 2: Longitudinal Stability & Articulation Velocity Trajectory
    """
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.2, 2.25), dpi=220)
    fig.patch.set_facecolor("#FAF9F5")

    # ---------------- PANEL 1: VOWEL SPACE TRIANGLE ----------------
    ax1.set_facecolor("#FAF9F5")
    
    # Standard healthy reference vowel space coordinates (Hz)
    # Normative: /i/ (F1 ~ 280, F2 ~ 2250), /u/ (F1 ~ 320, F2 ~ 850), /a/ (F1 ~ 750, F2 ~ 1250)
    norm_f1 = [280, 750, 320, 280]
    norm_f2 = [2250, 1250, 850, 2250]

    # Plot Normative Triangle (Dotted Matcha)
    ax1.plot(norm_f2, norm_f1, color="#46734C", linestyle="--", linewidth=1.1, label="Typical adult vowels (approx.)", alpha=0.7)
    ax1.scatter(norm_f2[:-1], norm_f1[:-1], color="#46734C", s=24, zorder=5)

    # Measured patient F1/F2 scatter: mean +/- 1 SD over voiced frames (Solid Warm Terracotta)
    if metrics["formant_compression_index"] is None:
        ax1.text(0.5, 0.5, "No result (too little voiced audio)", ha="center", va="center", transform=ax1.transAxes, fontsize=7, color="#383D36")
    else:
        ax1.add_patch(patches.Ellipse((metrics["mean_f2"], metrics["mean_f1"]), 2 * metrics["f2_dispersion"], 2 * metrics["f1_dispersion"], fill=False, edgecolor="#D87D65", linewidth=1.6, label="Patient (mean ± 1 SD)"))
        ax1.scatter([metrics["mean_f2"]], [metrics["mean_f1"]], color="#D87D65", s=28, zorder=6)

    # Annotate Vowel Anchors
    vowels = ["/i/", "/a/", "/u/"]
    for i, v in enumerate(vowels):
        ax1.annotate(v, (norm_f2[i] + 35, norm_f1[i] - 12), fontsize=7, color="#1A2620", fontweight="semibold")

    # Invert axes per clinical phonetics convention: F2 high-to-low on X, F1 low-to-high on Y
    ax1.invert_xaxis()
    ax1.invert_yaxis()
    ax1.set_title("Vowel Articulation Space (F1 vs F2)", fontsize=7.5, fontweight="bold", color="#1A2620", pad=5)
    ax1.set_xlabel("F2 Formant (Hz)", fontsize=6.5, color="#383D36")
    ax1.set_ylabel("F1 Formant (Hz)", fontsize=6.5, color="#383D36")
    ax1.tick_params(colors="#383D36", labelsize=6, pad=2)
    ax1.grid(True, linestyle=":", alpha=0.45, color="#A8B5AA")
    ax1.legend(loc="lower left", fontsize=6, frameon=True, facecolor="#F2F7F3", edgecolor="#D2DDD4")

    # ---------------- PANEL 2: LONGITUDINAL TRAJECTORY ----------------
    ax2.set_facecolor("#FAF9F5")

    if history and len(history) >= 2:
        sessions = [f"S{i+1}" for i in range(len(history))]
        velocities = [float(h["articulation_velocity"]) for h in history]
    else:
        sessions, velocities = [], []
        ax2.text(0.5, 0.5, "No longitudinal data", ha="center", va="center", transform=ax2.transAxes, fontsize=7, color="#383D36")

    x = np.arange(len(sessions))
    ax2.plot(x, velocities, color="#46734C", marker="o", linewidth=1.6, markersize=4, label="Articulation Velocity (syll/s)")
    
    # Healthy band
    ax2.axhspan(3.8, 5.2, color="#EAF1EB", alpha=0.6, label="Approx. adult range (3.8-5.2)")
    ax2.set_xticks(x)
    ax2.set_xticklabels(sessions, fontsize=6, color="#383D36")
    ax2.set_ylim(1.0, 5.4)
    ax2.set_title("Articulation Velocity Progression", fontsize=7.5, fontweight="bold", color="#1A2620", pad=5)
    ax2.set_xlabel("Clinical Session Timeline", fontsize=6.5, color="#383D36")
    ax2.set_ylabel("Syllables / Sec", fontsize=6.5, color="#383D36")
    ax2.tick_params(colors="#383D36", labelsize=6, pad=2)
    ax2.grid(True, linestyle=":", alpha=0.45, color="#A8B5AA")
    ax2.legend(loc="lower right", fontsize=6, frameon=True, facecolor="#F2F7F3", edgecolor="#D2DDD4")

    # Visual polish
    for ax in (ax1, ax2):
        for spine in ax.spines.values():
            spine.set_color("#D2DDD4")
            spine.set_linewidth(0.8)

    plt.tight_layout(pad=1.0)
    buf = io.BytesIO()
    plt.savefig(buf, format="png", dpi=220, facecolor=fig.get_facecolor(), edgecolor="none")
    buf.seek(0)
    plt.close(fig)
    return buf


def generate_clinical_pdf(report_data: Dict[str, Any], output_path: Optional[str] = None) -> bytes:
    """
    Assembles the one-page session report.

    Parameters:
    - report_data: dictionary containing:
        - patient: Dict with name, id (pseudonymous), condition (the clinician's wording), clinician
        - biomarkers: the biomarker_logs columns, plus mean_f1/mean_f2/f1_dispersion/f2_dispersion for the vowel chart
        - utterances: List of dicts with original_text, repaired_text, latency_ms
        - slp_assessment: Dict with impression, recommendation, exercises, frequency
        - history: Optional longitudinal trend items
    - output_path: Optional local file path to save PDF directly
    
    Returns:
    - bytes: Generated PDF byte buffer
    """
    pdf_buffer = io.BytesIO()

    # Letter size is 612 x 792 pt. Margins 34 pt leaves 544 pt width and 728 pt usable height.
    doc = SimpleDocTemplate(
        pdf_buffer,
        pagesize=letter,
        leftMargin=34,
        rightMargin=34,
        topMargin=32,
        bottomMargin=32,
    )

    # Attach session id to canvas instance for dynamic headers
    session_id = report_data.get("session_id", f"EPK-{int(time.time()) % 1000000:06d}")

    # Typography & Styles
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=15,
        textColor=COLOR_DEEP_PINE,
    )

    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=7.5,
        leading=9.5,
        textColor=COLOR_SLATE,
    )

    section_header_style = ParagraphStyle(
        "SectionHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=10.5,
        textColor=COLOR_DEEP_PINE,
        spaceBefore=3,
        spaceAfter=1.5,
    )

    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=7,
        leading=8.8,
        textColor=COLOR_SLATE,
    )

    bold_label_style = ParagraphStyle(
        "BoldLabel",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=7,
        leading=8.8,
        textColor=COLOR_DEEP_PINE,
    )

    table_header_style = ParagraphStyle(
        "TableHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=6.8,
        leading=8.2,
        textColor=COLOR_DEEP_PINE,
        alignment=TA_CENTER,
    )

    table_cell_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=6.8,
        leading=8.2,
        textColor=COLOR_SLATE,
    )

    table_cell_center = ParagraphStyle(
        "TableCellCenter",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=6.8,
        leading=8.2,
        textColor=COLOR_SLATE,
        alignment=TA_CENTER,
    )

    story = []

    # ---------------------------------------------------------------------------
    # 1. HEADER
    # ---------------------------------------------------------------------------
    eval_date = report_data.get("evaluation_date", datetime.now().strftime("%B %d, %Y"))

    header_table_data = [
        [
            Paragraph("<b>EPAKO VOICE AI</b>  |  SPEECH SESSION REPORT", ParagraphStyle("Brand", fontName="Helvetica-Bold", fontSize=10, leading=12, textColor=COLOR_CELADON)),
            Paragraph(f"<b>Date:</b> {escape(str(eval_date))}", ParagraphStyle("DateRight", fontName="Helvetica", fontSize=7.5, leading=9, textColor=COLOR_SLATE, alignment=TA_RIGHT))
        ],
        [
            Paragraph("Speech Session: Automated Acoustic Measurements", title_style),
            Paragraph(f"<b>Session Code:</b> {escape(str(session_id))}", ParagraphStyle("CodeRight", fontName="Helvetica", fontSize=7.5, leading=9, textColor=COLOR_SLATE, alignment=TA_RIGHT))
        ],
        [
            Paragraph("For review by the treating speech-language pathologist", subtitle_style),
            ""
        ]
    ]

    header_table = Table(header_table_data, colWidths=[385, 159])
    header_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
        ("TOPPADDING", (0, 0), (-1, -1), 0.5),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(header_table)
    story.append(Spacer(1, 3))

    # ---------------------------------------------------------------------------
    # 2. PATIENT STRIP
    # ---------------------------------------------------------------------------
    pt = report_data["patient"]
    patient_name = pt["name"]
    patient_id = pt["id"]
    condition = pt["condition"]
    clinician = pt["clinician"]

    patient_grid_data = [
        [
            Paragraph("<b>Patient Name:</b>", bold_label_style),
            Paragraph(escape(str(patient_name)), body_style),
            Paragraph("<b>Patient ID:</b>", bold_label_style),
            Paragraph(escape(str(patient_id)), body_style),
        ],
        [
            Paragraph("<b>Clinician:</b>", bold_label_style),
            Paragraph(escape(str(clinician)), body_style),
            Paragraph("<b>Condition (clinician):</b>", bold_label_style),
            Paragraph(escape(str(condition)), body_style),
        ]
    ]

    patient_table = Table(patient_grid_data, colWidths=[88, 184, 92, 180])
    patient_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), COLOR_MUTED_BG),
        ("BOX", (0, 0), (-1, -1), 0.6, COLOR_BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, COLOR_BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(patient_table)
    story.append(Spacer(1, 4))

    # ---------------------------------------------------------------------------
    # 3. ACOUSTIC MEASUREMENTS: compared with reference values, never interpreted as a diagnosis
    # ---------------------------------------------------------------------------
    story.append(Paragraph("Acoustic Measurements (automated, not clinically validated)", section_header_style))

    bio = report_data["biomarkers"]
    vel = float(bio["articulation_velocity"])
    pause_ratio = float(bio["pause_ratio"]) * 100
    jitter = float(bio["vocal_jitter_pct"])
    shimmer = float(bio["vocal_shimmer_pct"])
    cmp_idx = bio["formant_compression_index"]
    stability = float(bio["stability_index"])

    def compared(value, low=None, high=None):
        if low is not None and value < low:
            return Paragraph("Below reference", table_cell_center)
        if high is not None and value > high:
            return Paragraph("Above reference", table_cell_center)
        return Paragraph("Within reference", table_cell_center)

    biomarker_rows = [
        [
            Paragraph("Measure", table_header_style),
            Paragraph("This session", table_header_style),
            Paragraph("Reference value", table_header_style),
            Paragraph("Compared with reference", table_header_style),
        ],
        [
            Paragraph("<b>Articulation rate</b> (syllables per second while speaking)", table_cell_style),
            Paragraph(f"<b>{vel:.2f} syll / sec</b>", table_cell_center),
            Paragraph("3.80 - 5.20 syll / s (approximate adult range)", table_cell_center),
            compared(vel, 3.8, 5.2),
        ],
        [
            Paragraph("<b>Pause ratio</b> (share of the recording in pauses)", table_cell_style),
            Paragraph(f"<b>{pause_ratio:.1f} %</b>", table_cell_center),
            Paragraph("12.0 - 22.0 % (approximate)", table_cell_center),
            compared(pause_ratio, 12.0, 22.0),
        ],
        [
            Paragraph("<b>Pitch variation</b> (frame-level jitter estimate)", table_cell_style),
            Paragraph(f"<b>{jitter:.2f} %</b>", table_cell_center),
            Paragraph("1.04 % (MDVP cycle-level threshold; not directly comparable)", table_cell_center),
            compared(jitter, high=1.04),
        ],
        [
            Paragraph("<b>Loudness variation</b> (frame-level shimmer estimate)", table_cell_style),
            Paragraph(f"<b>{shimmer:.2f} %</b>", table_cell_center),
            Paragraph("3.81 % (MDVP cycle-level threshold; not directly comparable)", table_cell_center),
            compared(shimmer, high=3.81),
        ],
        [
            Paragraph("<b>Formant Compression Index</b> (pooled F1/F2 scatter)", table_cell_style),
            Paragraph("<b>no result</b>" if cmp_idx is None else f"<b>{float(cmp_idx):.3f}</b>", table_cell_center),
            Paragraph("None", table_cell_center),
            Paragraph("Not compared", table_cell_center),
        ],
        [
            Paragraph("<b>Composite stability score</b> (hand-set weights)", table_cell_style),
            Paragraph(f"<b>{stability:.1f} / 100</b>", table_cell_center),
            Paragraph("None", table_cell_center),
            Paragraph("Not compared", table_cell_center),
        ],
    ]

    biomarker_table = Table(biomarker_rows, colWidths=[168, 120, 130, 126])
    biomarker_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), COLOR_CELADON_LIGHT),
        ("BOX", (0, 0), (-1, -1), 0.6, COLOR_BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, COLOR_BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, COLOR_CELADON_TINT]),
        ("TOPPADDING", (0, 0), (-1, -1), 1.8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1.8),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(biomarker_table)
    story.append(Spacer(1, 4))

    # ---------------------------------------------------------------------------
    # 4. ACOUSTIC CHARTS (VOWEL SPACE & VELOCITY TRAJECTORY)
    # ---------------------------------------------------------------------------
    story.append(Paragraph("Vowel Space and Articulation Rate Across Sessions", section_header_style))
    with _CHART_LOCK:
        chart_buf = generate_acoustic_charts(bio, report_data.get("history"))
    chart_img = Image(chart_buf, width=544, height=140)
    story.append(chart_img)
    story.append(Spacer(1, 4))

    # ---------------------------------------------------------------------------
    # 5. SPEECH SAMPLES
    # ---------------------------------------------------------------------------
    story.append(Paragraph("Speech Samples From This Session", section_header_style))

    utterances = report_data["utterances"]

    utt_rows = [
        [
            Paragraph("What the recogniser heard", table_header_style),
            Paragraph("What the patient confirmed they meant", table_header_style),
            Paragraph("Latency", table_header_style),
        ]
    ]

    for u in utterances[:2]:
        utt_rows.append([
            Paragraph(f'<i>"{escape(str(u["original_text"]))}"</i>', table_cell_style),
            Paragraph(f'<b>"{escape(str(u["repaired_text"]))}"</b>', table_cell_style),
            Paragraph(f"{u['latency_ms']:.1f} ms", table_cell_center),
        ])

    utt_table = Table(utt_rows, colWidths=[240, 244, 60])
    utt_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), COLOR_CELADON_LIGHT),
        ("BOX", (0, 0), (-1, -1), 0.6, COLOR_BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, COLOR_BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, COLOR_CELADON_TINT]),
        ("TOPPADDING", (0, 0), (-1, -1), 1.8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1.8),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(utt_table)
    story.append(Spacer(1, 4))

    # ---------------------------------------------------------------------------
    # 6. SLP CLINICAL IMPRESSION & RECOMMENDATIONS
    # ---------------------------------------------------------------------------
    story.append(Paragraph("Speech-Language Pathologist Assessment &amp; Treatment Plan", section_header_style))

    slp = report_data["slp_assessment"]
    impression = slp["impression"]
    home_plan = slp["home_plan"]
    freq = slp["frequency"]

    plan_table_data = [
        [
            Paragraph("<b>Clinical Impression:</b>", bold_label_style),
            Paragraph(escape(str(impression)), body_style)
        ],
        [
            Paragraph("<b>Home practice:</b>", bold_label_style),
            Paragraph(escape(str(home_plan)), body_style)
        ],
        [
            Paragraph("<b>Frequency:</b>", bold_label_style),
            Paragraph(escape(str(freq)), body_style)
        ]
    ]

    plan_table = Table(plan_table_data, colWidths=[96, 448])
    plan_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), COLOR_MUTED_BG),
        ("BOX", (0, 0), (-1, -1), 0.6, COLOR_BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.3, COLOR_BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(plan_table)
    story.append(Spacer(1, 4))
    story.append(Paragraph(
        "<b>About this report.</b> The measurements are computed automatically from the session recording. They have "
        "not been clinically validated and are not a diagnosis. Reference values are approximate and for orientation only; "
        "pitch and loudness variation here are frame-level estimates, not the cycle-level measures the MDVP thresholds "
        "describe. Interpretation belongs to the treating speech-language pathologist.", body_style))
    story.append(Spacer(1, 4))

    # ---------------------------------------------------------------------------
    # 7. CLINICIAN SIGNATURE & DIGITAL AUDIT BLOCK
    # ---------------------------------------------------------------------------
    sig_data = [
        [
            Paragraph(f"<b>Attending Clinician:</b> {escape(str(clinician))}", body_style),
            Paragraph(f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}", ParagraphStyle("TimeRight", fontName="Helvetica", fontSize=6.5, leading=8, textColor=COLOR_SLATE, alignment=TA_RIGHT))
        ]
    ]

    sig_table = Table(sig_data, colWidths=[315, 229])
    sig_table.setStyle(TableStyle([
        ("LINEABOVE", (0, 0), (-1, 0), 0.5, COLOR_BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 1.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(sig_table)

    # Build PDF
    doc.build(story, canvasmaker=functools.partial(NumberedCanvas, session_id=session_id))
    pdf_bytes = pdf_buffer.getvalue()
    pdf_buffer.close()

    if output_path:
        with open(output_path, "wb") as f:
            f.write(pdf_bytes)
        print(f"[+] Clinical PDF Report successfully generated: {output_path} ({len(pdf_bytes)} bytes)")

    return pdf_bytes

